#!/usr/bin/env node
'use strict';
// Download and compress Free Exercise DB clips for a PERSONAL offline preview.
// The source repo offers a download-all script and describes rehosting.
// This must not be treated as independent verification of video ownership.
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),vm=require('node:vm');
const {spawn}=require('node:child_process');
const asset='app/src/main/assets',out=path.join(asset,'offline-videos');
const posters=path.join(out,'posters'),tmp=fs.mkdtempSync(path.join(os.tmpdir(),'fit-videos-'));
fs.mkdirSync(posters,{recursive:true});
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(asset,'free-exercise-data.js'),'utf8'),context,{timeout:30000});
const records=context.window.FitFreeExerciseData;
if(!Array.isArray(records)||records.length!==317)throw Error('Expected 317 exercise records');
const priority=['0025','drv-cable-bar-lateral-pulldown-wide-shoulder-grip','1435','0314','0208','2611','0289','0599','0464','0334','0175','0294','1723','drv-squat','drv-push-ups','0274','2188','0027','0298','0116','0417','0308','1429','0974','0218','2138','drv-treadmill-running'];
const ordering=new Map(priority.map((id,i)=>['free_'+id,i]));
const queue=[...records].sort((a,b)=>(ordering.get(a.id)??1000)-(ordering.get(b.id)??1000));
const limit=Math.min(317,Math.max(1,parseInt(process.env.FIT_VIDEO_LIMIT||'317',10)||317));
queue.length=limit;
const workers=Math.max(1,Math.min(10,parseInt(process.env.FIT_VIDEO_WORKERS||'6',10)||6));
const succeeded=[],failed=[];
let next=0;
function run(cmd,args){
 return new Promise((resolve,reject)=>{
  const child=spawn(cmd,args,{stdio:['ignore','ignore','pipe']});
  let err='';child.stderr.on('data',d=>err=(err+d.toString()).slice(-1500));
  child.on('error',reject);
  child.on('close',c=>c===0?resolve():reject(Error(cmd+' exited '+c+' '+err)));
 });
}
async function convert(item){
 const id=item.id.slice(5),input=path.join(tmp,id+'.mp4');
 const output=path.join(out,id+'.mp4'),poster=path.join(posters,id+'.jpg');
 try{
  if(!/^[a-z0-9-]+$/.test(id)||!/^https:\/\/pub-[a-z0-9]+\.r2\.dev\/exercise-videos\/(male|female)\/[a-z0-9-]+\.mp4$/.test(item.video))
   throw Error('Invalid id or source URL');
  await run('curl',['-fSL','--retry','2','--retry-all-errors','--connect-timeout','15','--max-time','150',item.video,'-o',input]);
  if(fs.statSync(input).size<8000)throw Error('Source video missing');
  await run('ffmpeg',['-hide_banner','-loglevel','error','-nostdin','-y','-i',input,'-an',
   '-vf','scale=640:360:force_original_aspect_ratio=decrease:force_divisible_by=2,fps=18',
   '-c:v','libx264','-preset','veryfast','-crf','30','-maxrate','550k','-bufsize','1100k',
   '-threads','1','-pix_fmt','yuv420p','-movflags','+faststart',output]);
  if(fs.statSync(output).size<5000)throw Error('Encoded MP4 too small');
  await run('ffmpeg',['-hide_banner','-loglevel','error','-nostdin','-y','-ss','0.5','-i',input,
    '-frames:v','1','-vf','scale=320:180:force_original_aspect_ratio=decrease','-q:v','6',poster]);
  if(fs.statSync(poster).size<200)throw Error('Invalid JPEG poster');
  succeeded.push(id);
  console.log('OK '+succeeded.length+' '+id+' '+Math.round(fs.statSync(output).size/1024)+' KB');
 }catch(e){
  failed.push([id,String(e.message).slice(0,200)]);
  fs.rmSync(output,{force:true});fs.rmSync(poster,{force:true});
  console.error('FAIL '+id+' '+String(e.message).slice(0,200));
 }finally{fs.rmSync(input,{force:true})}
}
async function worker(){while(next<queue.length){let i=next++;await convert(queue[i])}}
function createIndex(){
 const available=new Set(succeeded);
 const mapped=records.filter(m=>available.has(m.id.slice(5))).map(m=>{
  const id=m.id.slice(5);
  return [m.id,'offline-videos/'+id+'.mp4','offline-videos/posters/'+id+'.jpg'];
 });
 const js="/* Generated by tools/build-offline-videos.cjs: only files inside APK are included. */\n"+
 "(function(){'use strict';\n"+
 "const byId=new Map("+JSON.stringify(mapped)+".map(([id,video,poster])=>[id,{video,poster}]));\n"+
 "const full=window.FitFreeExerciseData||[];\n"+
 "const oldURLs=new Map(full.map(x=>[x.video,x.id]));\n"+
 "const selected=full.filter(x=>byId.has(x.id)).map(x=>Object.assign(x,byId.get(x.id),{offline:true,source:'Free Exercise DB · APK',videoFemale:null,posterFemale:null}));\n"+
 "const alias={};for(const [key,clip] of Object.entries(window.FitLegacyVideoMatches||{})){const id=oldURLs.get(clip.video);if(id&&byId.has(id))alias[key]={...clip,...byId.get(id),offline:true,source:'Free Exercise DB · APK'};}\n"+
 "window.FitFreeExerciseData=selected;\n"+
 "window.FitFreeVideoClips=Object.fromEntries(selected.map(x=>[x.id,x]));\n"+
 "window.FitLegacyVideoMatches=alias;\n"+
 "window.FitOfflineVideoCount=selected.length;\n"+
 "window.FitOfflineVideoIds=selected.map(x=>x.id);\n"+
 "})();\n";
 fs.writeFileSync(path.join(asset,'offline-video-index.js'),js);
 const bytes=succeeded.reduce((n,id)=>n+fs.statSync(path.join(out,id+'.mp4')).size,0);
 console.log('OFFLINE_BUNDLED '+succeeded.length+'/'+limit+' FILE_MB='+(bytes/1048576).toFixed(1)+' FAILED='+failed.length);
 fs.writeFileSync(path.join(asset,'OFFLINE_VIDEO_CREDITS.txt'),
  'Personal FitKoçum test build using Free Exercise DB with Videos: https://github.com/harshvishu/free-exercise-db-with-videos . Source README describes video rehosting; video ownership is not independently verified. Exercise metadata MIT (c) 2026 Arham Wani.\n');
}
async function main(){
 await Promise.all(Array.from({length:workers},worker));
 createIndex();
 fs.rmSync(tmp,{recursive:true,force:true});
 for(const id of priority.slice(0,13))if(!succeeded.includes(id))throw Error('Essential offline video missing: '+id);
 if(succeeded.length<Math.min(50,limit))throw Error('Too few videos');
 if(failed.length>12)throw Error('Too many missing clips: '+failed.length);
}
main().catch(e=>{console.error(e);process.exitCode=1});
