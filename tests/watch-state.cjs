'use strict';
// Pure Watch v4.2 state and packet validation: does not claim hardware testing.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('watch-lite/entry/src/main/js/MainAbility/utils/watch-state.js','utf8');
const sandbox={};
vm.runInNewContext(source.replace('export default {','globalThis.EXPORTED={'),sandbox,{timeout:12000});
const core=sandbox.EXPORTED;
assert.equal(core.MOVES.length,5);
assert.ok(core.MOVES.every(x=>x.video.endsWith('.mp4')&&x.poster.endsWith('.png')));
const initial=core.fresh();
assert.equal(core.current(initial).id,'0025');
let state=core.choose(initial,1);
assert.equal(core.current(state).title,'LAT PULLDOWN');
state=core.choose(state,-1);
assert.equal(state.index,4);
state=core.choose(initial,0);
const stamp=Date.now();
const r=core.complete(state,stamp);
assert.ok(r.event);
assert.equal(r.event.type,'set.completed');
assert.equal(r.event.payload.exerciseId,'0025');
assert.equal(r.event.payload.setNumber,1);
assert.equal(core.restRemaining(r.state,stamp),90);
assert.equal(core.restFormat(90),'01:30');
assert.equal(core.restRemaining(r.state,stamp+90001),0);
assert.equal(core.fromSaved(core.toSaved(r.state)).counts[0],1);
assert.equal(core.fromSaved(core.toSaved(r.state)).restUntil,stamp+90000);
assert.equal(core.fromSaved('evil').counts[0],0);
let wrong={v:1,type:'exercise.select',messageId:'message-0001',payload:{exerciseId:'bad-clip'}};
assert.equal(core.validateMessage(wrong),false);
const good={...wrong,payload:{exerciseId:'1435'}};
assert.equal(core.validateMessage(good),true);
const applied=core.onMessage(r.state,good,stamp+1500);
assert.equal(applied.accepted,true);
assert.equal(core.current(applied.state).title,'SQUAT');
assert.equal(core.onMessage(applied.state,good,stamp+1501).reason,'duplicate');
const rest={v:1,type:'rest.start',messageId:'message-0002',payload:{seconds:45}};
assert.equal(core.restRemaining(core.onMessage(applied.state,rest,stamp).state,stamp),45);
const ack={v:1,type:'ack',messageId:'message-0003',payload:{messageId:r.event.messageId}};
assert.equal(core.onMessage(r.state,ack,stamp).state.pending.length,0);
const invalid={v:1,type:'rest.start',messageId:'message-0004',payload:{seconds:9000}};
assert.equal(core.validateMessage(invalid),false);
const accepted={v:1,type:'set.completed',messageId:'message-0005',payload:{exerciseId:'0025',setNumber:2,occurredAt:stamp}};
const after=core.onMessage(r.state,accepted,stamp);
assert.equal(after.state.counts[0],1,'incoming set must not bypass phone confirmation');
console.log('PASS: 5 exercise assets, persistent watch sets, 90s timer, strict messages, dedup, ACK');
